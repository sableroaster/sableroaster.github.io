// Pre-renders the home headline to SVG path data so the site needn't ship opentype.js + the font.
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const TEXT = "กาแฟดี ๆ ใต้ร่มไม้";
const FONT_SIZE = 96;
const PAD = 5;

const buf = readFileSync(new URL("./fonts/Mali-Bold.ttf", import.meta.url));
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const b = font.getPath(TEXT, 0, FONT_SIZE, FONT_SIZE).getBoundingBox();
const path = font.getPath(TEXT, PAD - b.x1, FONT_SIZE + PAD - b.y1, FONT_SIZE);
const width = Math.ceil(b.x2 - b.x1) + 2 * PAD;
const height = Math.ceil(b.y2 - b.y1) + 2 * PAD;
const d = path.toPathData(2);

// Self-check: the shifted path must sit inside the viewBox.
const nb = path.getBoundingBox();
const eps = 0.01;
if (!d || width <= 0 || height <= 0 || nb.x1 < -eps || nb.y1 < -eps || nb.x2 > width + eps || nb.y2 > height + eps) {
  throw new Error(`Bad output: ${JSON.stringify({ width, height, bbox: nb, dLength: d.length })}`);
}

writeFileSync(
  new URL("../src/generated/handwriting.ts", import.meta.url),
  `// Generated by scripts/gen-handwriting.mjs — do not edit.\nexport const HEADLINE = { d: ${JSON.stringify(d)}, width: ${width}, height: ${height} } as const;\n`,
);
console.log(`HEADLINE ${width}x${height}, d ${d.length} chars, bbox`, nb);
